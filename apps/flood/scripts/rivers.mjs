// Builds src/data/rivers.ts: the main rivers of Bulgaria as SVG paths in the oblast map's coordinates.
// Source: Natural Earth 1:10m rivers (public domain): "rivers_europe" plus the Danube, Maritsa and Struma from
// "rivers_lake_centerlines". `npm run rivers -- --download` refreshes scripts/data/bg-rivers.geojson from
// GitHub; without it the committed copy is used.
import { readFileSync, writeFileSync } from "node:fs";

const SRC = new URL("./data/bg-rivers.geojson", import.meta.url);
const NE = "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/";
// Natural Earth name → Bulgarian and English name shown on the map.
const KEEP = {
  Danube: ["Дунав", "Danube"],
  Maritsa: ["Марица", "Maritsa"],
  Evros: ["Марица", "Maritsa"],
  Strimonas: ["Струма", "Struma"],
  Strymnas: ["Струма", "Struma"],
  Mesta: ["Места", "Mesta"],
  Arda: ["Арда", "Arda"],
  Tundzha: ["Тунджа", "Tundzha"],
  "Levi Iskar": ["Искър", "Iskar"],
  Yantra: ["Янтра", "Yantra"],
  Ogosta: ["Огоста", "Ogosta"],
  Kamchiya: ["Камчия", "Kamchia"],
};
const BBOX = [22.3, 41.2, 28.7, 44.3];

if (process.argv.includes("--download")) {
  const features = [];
  for (const f of ["ne_10m_rivers_europe", "ne_10m_rivers_lake_centerlines"]) {
    const fc = await (await fetch(`${NE}${f}.geojson`)).json();
    for (const ft of fc.features) {
      const name = ft.properties.name;
      if (!KEEP[name] || !ft.geometry) continue;
      const lines = ft.geometry.type === "MultiLineString" ? ft.geometry.coordinates : [ft.geometry.coordinates];
      const near = lines.some((l) => l.some(([x, y]) => x > BBOX[0] - 0.3 && x < BBOX[2] + 0.3 && y > BBOX[1] - 0.3 && y < BBOX[3] + 0.3));
      if (near) features.push({ type: "Feature", properties: { name }, geometry: { type: "MultiLineString", coordinates: lines } });
    }
  }
  writeFileSync(SRC, JSON.stringify({ type: "FeatureCollection", features }));
  console.log("downloaded", features.length, "features");
}

// The oblast map's projection (scripts in packages/core write it into oblasts.ts).
const oblasts = readFileSync(new URL("../../../packages/core/src/data/oblasts.ts", import.meta.url), "utf8");
const m = /\(lon \* ([\d.]+) - ([\d.]+)\) \* ([\d.]+) \+ 8, \(([\d.]+) - lat\) \* ([\d.]+) \+ 8/.exec(oblasts);
if (!m) throw new Error("projection not found in oblasts.ts");
const [kx, bx, s, lat0] = [Number(m[1]), Number(m[2]), Number(m[3]), Number(m[4])];
const project = (lat, lon) => [(lon * kx - bx) * s + 8, (lat0 - lat) * s + 8];

// Bulgaria's border, to drop the parts of rivers that run in other countries. The Danube is the border itself,
// so it is kept along its whole Bulgarian stretch instead.
const border = JSON.parse(readFileSync(new URL("../../../packages/core/src/data/bulgaria.json", import.meta.url), "utf8")).geometry.coordinates[0];
function inBulgaria(lat, lon) {
  let inside = false;
  for (let i = 0, j = border.length - 1; i < border.length; j = i++) {
    const [xi, yi] = border[i];
    const [xj, yj] = border[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

/** Ramer–Douglas–Peucker in SVG units. */
function simplify(pts, tol) {
  if (pts.length < 3) return pts;
  const [a, b] = [pts[0], pts[pts.length - 1]];
  let max = 0;
  let k = 0;
  for (let i = 1; i < pts.length - 1; i++) {
    const [x, y] = pts[i];
    const dx = b[0] - a[0];
    const dy = b[1] - a[1];
    const d = Math.abs(dy * x - dx * y + b[0] * a[1] - b[1] * a[0]) / (Math.hypot(dx, dy) || 1);
    if (d > max) [max, k] = [d, i];
  }
  if (max <= tol) return [a, b];
  return [...simplify(pts.slice(0, k + 1), tol).slice(0, -1), ...simplify(pts.slice(k), tol)];
}

const fc = JSON.parse(readFileSync(SRC, "utf8"));
const byName = new Map();
for (const ft of fc.features) {
  const [bg, en] = KEEP[ft.properties.name];
  const danube = bg === "Дунав";
  for (const line of ft.geometry.coordinates) {
    let run = [];
    const flush = () => {
      if (run.length > 1) {
        const pts = simplify(run.map(([lon, lat]) => project(lat, lon)), 0.6);
        const d = "M" + pts.map(([x, y]) => `${x.toFixed(1)} ${y.toFixed(1)}`).join("L");
        byName.set(bg, { bg, en, d: (byName.get(bg)?.d ?? "") + d, major: danube });
      }
      run = [];
    };
    for (const [lon, lat] of line) {
      const keep = danube ? lon > 22.6 && lon < 28.0 && lat > 43.5 && lat < 44.3 : inBulgaria(lat, lon);
      if (keep) run.push([lon, lat]);
      else flush();
    }
    flush();
  }
}

const rivers = [...byName.values()];
writeFileSync(
  new URL("../src/data/rivers.ts", import.meta.url),
  `// Generated by scripts/rivers.mjs from Natural Earth 1:10m rivers (public domain). Do not edit.
// Paths are in the coordinates of the oblast map (packages/core/src/data/oblasts.ts).
export type River = { bg: string; en: string; d: string; major: boolean };

export const RIVERS: River[] = ${JSON.stringify(rivers)};
`,
);
