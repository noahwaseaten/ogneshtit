// Builds src/data/oblasts.ts: SVG paths for Bulgaria's 28 oblasts.
// Source: Natural Earth admin-1 boundaries (public domain), trimmed in scripts/data/bg-oblasts.geojson.
// Run: node scripts/oblasts.mjs
import { readFileSync, writeFileSync } from "node:fs";

const NAMES = {
  "BG-01": "Благоевград", "BG-02": "Бургас", "BG-03": "Варна", "BG-04": "Велико Търново",
  "BG-05": "Видин", "BG-06": "Враца", "BG-07": "Габрово", "BG-08": "Добрич", "BG-09": "Кърджали",
  "BG-10": "Кюстендил", "BG-11": "Ловеч", "BG-12": "Монтана", "BG-13": "Пазарджик", "BG-14": "Перник",
  "BG-15": "Плевен", "BG-16": "Пловдив", "BG-17": "Разград", "BG-18": "Русе", "BG-19": "Силистра",
  "BG-20": "Сливен", "BG-21": "Смолян", "BG-22": "София град", "BG-23": "София област",
  "BG-24": "Стара Загора", "BG-25": "Търговище", "BG-26": "Хасково", "BG-27": "Шумен", "BG-28": "Ямбол",
};

// Equirectangular projection scaled for Bulgaria's latitude: simple, and accurate enough at this size.
const K = Math.cos((42.75 * Math.PI) / 180);
const W = 1000;

const fc = JSON.parse(readFileSync(new URL("./data/bg-oblasts.geojson", import.meta.url), "utf8"));
const rings = (g) => (g.type === "Polygon" ? [g.coordinates] : g.coordinates).flat();

let minX = Infinity, maxX = -Infinity, minY = Infinity, maxY = -Infinity;
for (const f of fc.features)
  for (const ring of rings(f.geometry))
    for (const [lon, lat] of ring) {
      minX = Math.min(minX, lon * K); maxX = Math.max(maxX, lon * K);
      minY = Math.min(minY, -lat); maxY = Math.max(maxY, -lat);
    }
const PAD = 8;
const S = (W - PAD * 2) / (maxX - minX);
const H = Math.ceil((maxY - minY) * S + PAD * 2);
const px = (lon, lat) => [(lon * K - minX) * S + PAD, (-lat - minY) * S + PAD];
const r1 = (n) => Math.round(n * 10) / 10;

const oblasts = fc.features.map((f) => {
  const code = f.properties.iso;
  let d = "";
  let ax = 0, ay = 0, area = 0;
  for (const ring of rings(f.geometry)) {
    const pts = [];
    for (const [lon, lat] of ring) {
      const [x, y] = px(lon, lat).map(r1);
      const last = pts[pts.length - 1];
      if (!last || last[0] !== x || last[1] !== y) pts.push([x, y]);
    }
    d += "M" + pts.map((p) => p.join(" ")).join("L") + "Z";
    // Area-weighted centroid for the label.
    for (let i = 0; i < pts.length; i++) {
      const [x0, y0] = pts[i];
      const [x1, y1] = pts[(i + 1) % pts.length];
      const c = x0 * y1 - x1 * y0;
      area += c; ax += (x0 + x1) * c; ay += (y0 + y1) * c;
    }
  }
  return { code, name: NAMES[code], d, cx: r1(ax / (3 * area)), cy: r1(ay / (3 * area)) };
});

const out = `// Generated by scripts/oblasts.mjs from Natural Earth admin-1 boundaries (public domain). Do not edit.
export const MAP_W = ${W};
export const MAP_H = ${H};

/** Project a WGS84 point into the map's SVG coordinates. */
export function project(lat: number, lon: number): [number, number] {
  return [(lon * ${K} - ${minX}) * ${S} + ${PAD}, (${-minY} - lat) * ${S} + ${PAD}];
}

/** SVG units per kilometre, for drawing distances such as a 50 km ring. */
export const UNITS_PER_KM = ${S / 111.32};

export type Oblast = { code: string; name: string; d: string; cx: number; cy: number };

export const OBLASTS: Oblast[] = ${JSON.stringify(oblasts, null, 0).replace(/\},\{/g, "},\n  {")};
`;
writeFileSync(new URL("../src/data/oblasts.ts", import.meta.url), out);
console.log(`oblasts: ${oblasts.length} paths, ${W}×${H}, ${out.length} bytes`);
